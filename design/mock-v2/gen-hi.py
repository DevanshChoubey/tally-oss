#!/usr/bin/env python3
"""Writes hi.js: the Hindi words the mock shows for `lang=hi` states.

The words come from the app's own translation files, so the mock and the app can never disagree.
An English phrase that the app translates is replaced in the mock when it is a whole text node.
Run from this folder: python3 -I gen-hi.py
"""
import json, tomllib, pathlib
root = pathlib.Path(__file__).resolve().parents[2] / "crates/ledgerly-app/assets/i18n"


def flat(tree, prefix=""):
    out = {}
    for k, v in tree.items():
        if isinstance(v, dict):
            out.update(flat(v, prefix + k + "."))
        else:
            out[prefix + k] = v
    return out


en = flat(tomllib.loads((root / "en.toml").read_text(encoding="utf-8"))["strings"])
hi = flat(tomllib.loads((root / "hi.toml").read_text(encoding="utf-8"))["strings"])
words = {}
for key in sorted(en):
    if key not in hi or "{" in en[key] or key.startswith("format."):
        continue
    words.setdefault(en[key], hi[key])
months = {en[k]: hi[k] for k in en if k.startswith("format.month.") and k in hi}
full = {en[k]: hi[k] for k in en if k.startswith("format.month_full.") and k in hi}
full.update({en[k]: hi[k] for k in en if k.startswith("format.weekday.") and k in hi})
out = {"words": words, "months": months, "full": full}
(pathlib.Path(__file__).parent / "hi.js").write_text(
    "/* generated by gen-hi.py from the app's en.toml and hi.toml; do not edit */\nwindow.HI="
    + json.dumps(out, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
print(len(words), "words")
