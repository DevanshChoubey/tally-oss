// Writes captures/CATALOG.md: every state and transition of the mock with its captured images,
// grouped by screen. Run by capture.mjs after a full capture; it can also run alone.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'captures');
const states = JSON.parse(readFileSync(join(here, 'states.json'), 'utf8'));
const transitions = JSON.parse(readFileSync(join(here, 'transitions.json'), 'utf8'));
const manifest = existsSync(join(out, 'manifest.json'))
  ? JSON.parse(readFileSync(join(out, 'manifest.json'), 'utf8')) : null;
const themeName = { light: 'Light', dark: 'Dark', hc: 'High contrast' };
const cell = (text) => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');

const screens = new Map();
for (const s of states.states) {
  const screen = s.id.split('.')[0];
  if (!screens.has(screen)) screens.set(screen, []);
  screens.get(screen).push(s);
}

const lines = [
  '# Ledgerly mock v2: capture catalog',
  '',
  'Generated by `node capture.mjs` from `index.html`, `states.json` and `transitions.json`. Do not',
  'edit by hand. Run `node capture.mjs --check` to see whether the captures match the mock.',
  '',
  manifest
    ? `${manifest.states} states and ${manifest.transitions} transitions in ${manifest.themes.length} themes: ${manifest.images} images, ${manifest.errors.length} capture errors. Source sha256 \`${manifest.source_sha256.slice(0, 12)}\`.`
    : 'No manifest yet: run `node capture.mjs`.',
  '',
  '## Screens',
  '',
  [...screens.keys()].map((s) => `[${s}](#${s})`).join(' · '),
  '',
];

for (const [screen, list] of screens) {
  lines.push(`### ${screen}`, '', `| State | Kind | ${states.themes.map((t) => themeName[t]).join(' | ')} |`,
    `|---|---|${states.themes.map(() => '---').join('|')}|`);
  for (const s of list) {
    const images = states.themes.map((t) => {
      const path = `states/${t}/${s.id}.webp`;
      return `[<img src="${path}" width="240" alt="${cell(s.title)}, ${themeName[t]}">](${path})`;
    });
    lines.push(`| **${cell(s.title)}**<br>\`${s.id}\`<br>${cell(s.description)} | ${s.kind} | ${images.join(' | ')} |`);
  }
  lines.push('');
}

lines.push('## Transitions', '', 'Each GIF holds every frame for the gap to the next one, and the last frame for 600 ms. The',
  'single frames are in `transitions/<id>/<theme>/`.', '',
  `| Transition | Motion | ${transitions.themes.map((t) => themeName[t]).join(' | ')} |`,
  `|---|---|${transitions.themes.map(() => '---').join('|')}|`);
for (const t of transitions.transitions) {
  const gifs = transitions.themes.map((th) => {
    const path = `transitions/${t.id}/${th}.gif`;
    return `[<img src="${path}" width="240" alt="${cell(t.title)}, ${themeName[th]}">](${path})`;
  });
  const motion = `${t.kind}, ${t.duration_ms} ms, ${t.easing}<br>frames ${t.frames_ms.join(', ')} ms<br>\`${t.start}\` → \`${t.end}\``;
  lines.push(`| **${cell(t.title)}**<br>\`${t.id}\` | ${motion} | ${gifs.join(' | ')} |`);
}
lines.push('');

writeFileSync(join(out, 'CATALOG.md'), lines.join('\n'));
console.log(`wrote ${join(out, 'CATALOG.md')}`);
